'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
const modules = ['exporter','batch'];
const rewrite = code => code.replace(/require\(['"]\.\/([a-z-]+)['"]\)/g, (_, name) => {
  if (!modules.includes(name)) throw new Error('Unknown bundled module: ' + name);
  return 'load(' + JSON.stringify(name) + ')';
});
const factories = modules.map(name => JSON.stringify(name) + ': function(module,load){\n' + rewrite(read('src/'+name+'.js')) + '\n}').join(',\n');
const code = '(function(){\nconst factories={'+factories+'};\nconst cache={};\nfunction load(id){if(!cache[id]){const m={exports:{}};cache[id]=m;factories[id](m,load);}return cache[id].exports;}\n'+rewrite(read('src/main.js'))+'\n})();\n';
new vm.Script(code, { filename: 'dist/code.js' });
const zip = read('src/zip.js'), handoff = read('src/handoff.js'), ui = read('src/ui.js');
new vm.Script(zip); new vm.Script(handoff); new vm.Script(ui);
const html = read('src/ui.html').replace('/* ZIP_MODULE */', () => zip).replace('/* HANDOFF_MODULE */', () => handoff).replace('/* UI_MODULE */', () => ui);
fs.writeFileSync(path.join(root, 'dist/code.js'), code);
fs.writeFileSync(path.join(root, 'dist/ui.html'), html);
console.log('Built dist/code.js + dist/ui.html (no dependencies)');
